<script id="shiva-video-modal-script">
(function(){
  function initVideoModal(){
    var modal=document.getElementById('shiva-video-modal');
    var player=document.getElementById('shiva-video-player');
    if(!modal || !player) return;
    var closeBtn=modal.querySelector('.shiva-video-close');
    var backdrop=modal.querySelector('.shiva-video-backdrop');
    function close(){
      modal.classList.remove('is-open');
      modal.setAttribute('aria-hidden','true');
      player.pause();
      player.removeAttribute('src');
      player.load();
      document.body.classList.remove('shiva-video-open');
    }
    function open(src){
      if(!src) return;
      player.src=src;
      modal.classList.add('is-open');
      modal.setAttribute('aria-hidden','false');
      document.body.classList.add('shiva-video-open');
      player.play();
    }
    document.querySelectorAll('.shiva-video-trigger').forEach(function(btn){
      btn.addEventListener('click',function(e){
        e.preventDefault();
        e.stopPropagation();
        open(btn.getAttribute('data-video'));
      });
    });
    closeBtn.addEventListener('click',close);
    backdrop.addEventListener('click',close);
    document.addEventListener('keydown',function(e){ if(e.key==='Escape') close(); });
  }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',initVideoModal);
  else initVideoModal();
})();
</script>

