<script id="product-lightbox-gallery-js">
(function(){
  function initProductLightbox(){
    var lightbox=document.getElementById('productImageLightbox');
    var preview=document.getElementById('productLightboxPreview');
    var closeBtn=lightbox && lightbox.querySelector('.product-lightbox-close');
    var prevBtn=lightbox && lightbox.querySelector('.product-lightbox-prev');
    var nextBtn=lightbox && lightbox.querySelector('.product-lightbox-next');
    var counter=document.getElementById('productLightboxCounter');
    if(!lightbox || !preview) return;

    var items=[], index=0;

    function render(){
      if(!items.length) return;
      var item=items[index];
      preview.src=item.src;
      preview.alt=item.alt || 'Product image preview';
      if(counter) counter.textContent=(index+1)+' / '+items.length;
      if(prevBtn) prevBtn.style.display=items.length>1?'flex':'none';
      if(nextBtn) nextBtn.style.display=items.length>1?'flex':'none';
    }
    function openFromImage(img){
      var carousel=img.closest('.carousel');
      var imgs=carousel ? carousel.querySelectorAll('.carousel-item .product-img') : [img];
      items=Array.prototype.map.call(imgs,function(el){
        return {src:el.currentSrc || el.src,alt:el.alt || 'Product image'};
      }).filter(function(x){return !!x.src;});
      index=0;
      var current=img.currentSrc || img.src;
      var found=items.findIndex(function(x){return x.src===current;});
      if(found>=0) index=found;
      render();
      lightbox.classList.add('is-open');
      lightbox.setAttribute('aria-hidden','false');
      document.body.classList.add('product-lightbox-open');
    }
    function closeImage(){
      lightbox.classList.remove('is-open');
      lightbox.setAttribute('aria-hidden','true');
      document.body.classList.remove('product-lightbox-open');
      setTimeout(function(){
        if(!lightbox.classList.contains('is-open')){
          preview.src='';
          items=[];
          if(counter) counter.textContent='';
        }
      },180);
    }
    function move(step){
      if(items.length<2) return;
      index=(index+step+items.length)%items.length;
      render();
    }

    document.addEventListener('click',function(e){
      var img=e.target.closest && e.target.closest('.our-products-grid .product-img');
      if(img){
        e.preventDefault();
        e.stopPropagation();
        openFromImage(img);
        return;
      }
      var target=e.target.closest && e.target.closest('.our-products-grid .product-image-click-target');
      if(target){
        e.preventDefault();
        e.stopPropagation();
        var image=target.closest('.carousel-item') && target.closest('.carousel-item').querySelector('.product-img');
        if(image) openFromImage(image);
      }
    },true);

    document.querySelectorAll('.our-products-grid .product-img').forEach(function(img){
      img.setAttribute('role','button');
      img.setAttribute('tabindex','0');
      img.addEventListener('keydown',function(e){
        if(e.key==='Enter' || e.key===' '){
          e.preventDefault();
          openFromImage(img);
        }
      });
    });

    if(closeBtn) closeBtn.addEventListener('click',closeImage);
    if(prevBtn) prevBtn.addEventListener('click',function(e){e.stopPropagation();move(-1);});
    if(nextBtn) nextBtn.addEventListener('click',function(e){e.stopPropagation();move(1);});
    lightbox.addEventListener('click',function(e){if(e.target===lightbox) closeImage();});
    document.addEventListener('keydown',function(e){
      if(!lightbox.classList.contains('is-open')) return;
      if(e.key==='Escape') closeImage();
      else if(e.key==='ArrowLeft') move(-1);
      else if(e.key==='ArrowRight') move(1);
    });
  }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',initProductLightbox);
  else initProductLightbox();
})();
</script>
